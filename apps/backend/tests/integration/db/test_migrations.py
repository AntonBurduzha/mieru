def key_details(connection: Connection) -> dict[str, object]:
    """What the column names don't show, and command.check can't catch when the models agree."""
    inspector = inspect(connection)
    organization_columns = {
        column["name"]: column for column in inspector.get_columns("organizations")
    }
    site_columns = {column["name"]: column for column in inspector.get_columns("sites")}
    (foreign_key,) = inspector.get_foreign_keys("sites")
    return {
        "organizations.id default": organization_columns["id"]["default"],
        "sites.id always identity": site_columns["id"]["identity"]["always"],
        "sites.status default": site_columns["status"]["default"],
        "sites.rate_limit_per_min default": site_columns["rate_limit_per_min"]["default"],
        "sites.organization_id on delete": foreign_key["options"].get("ondelete"),
        "sites indexes": {index["name"] for index in inspector.get_indexes("sites")},
    }


async def test_the_keys_and_defaults_are_as_in_the_spec(db_session: AsyncSession) -> None:
    connection = await db_session.connection()
    assert await connection.run_sync(key_details) == {
        "organizations.id default": "gen_random_uuid()",
        "sites.id always identity": True,
        "sites.status default": "'active'::text",
        "sites.rate_limit_per_min default": "6000",
        "sites.organization_id on delete": "CASCADE",
        "sites indexes": {"ix_sites_organization_id", "uq_sites_domain"},
    }


async def insert_alone(session: AsyncSession, row: Site | Salt) -> None:
    """Insert one row in its own SAVEPOINT, so a refused row leaves the session usable."""
    async with session.begin_nested():
        session.add(row)
        await session.flush()


async def test_the_database_refuses_a_bad_status_and_a_short_salt(
    db_session: AsyncSession,
) -> None:
    organization = await make_organization(db_session)
    paused = Site(organization_id=organization.id, domain="a.test", timezone="UTC", status="paused")
    with pytest.raises(IntegrityError):
        await insert_alone(db_session, paused)
    with pytest.raises(IntegrityError):
        await insert_alone(db_session, Salt(day=date(2026, 11, 13), salt=b"too short"))
